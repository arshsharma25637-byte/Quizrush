export function pickRoundQuestions(category: CategoryId, count = QUESTIONS_PER_ROUND): Question[] {
  const pool =
    category === 'mix'
      ? [...QUESTION_BANK]
      : QUESTION_BANK.filter((q) => q.category === category);

  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool.slice(0, Math.min(count, pool.length));
}

export function getCategoryLabel(category: CategoryId, lang: QuizLanguage = 'en'): string {
  if (category === 'mix') return lang === 'hi' ? 'मेगा मिक्स' : 'Quick Mix';
  const found = CATEGORIES.find((c) => c.id === category);
  if (!found) return 'Trivia';
  return lang === 'hi' ? found.nameHi : found.name;
}
